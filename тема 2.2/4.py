מַסְקָנָה = 'На ресепшене нас встретил кудрявый семён, а донести багаж за чаевые помог ДАВИД.'
יַעַד1 = 'семён'
יַעַד2 = 'давид'
סְקִירָה_לְהוֹרִיד = מַסְקָנָה.lower()
מַצָב1 = סְקִירָה_לְהוֹרִיד.find(יַעַד1)
מַצָב2 = סְקִירָה_לְהוֹרִיד.find(יַעַד2)
מַעֲסִיק1 = מַסְקָנָה[מַצָב1 : מַצָב1 + len(יַעַד1)]
מַעֲסִיק2 = מַסְקָנָה[מַצָב2 : מַצָב2 + len(יַעַד2)]
מַעֲנָק = מַעֲסִיק1 + ', ' + מַעֲסִיק2
print('Сотрудники на премию:', מַעֲנָק)